// The /agent-config command inside each agent: one new file per agent, in the agent's own documented format.
// The installer only ever creates or replaces files that carry MARKER, and uninstall removes only those.
import { rm, rmdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import type { FileSystem } from '../core/ports.ts'
import { nodeFileSystem } from '../adapters/node-fs.ts'
import { AGENTS, type AgentId } from './args.ts'

/** Every file the installer writes contains this text; a file without it is never overwritten or removed. */
export const MARKER = 'Generated by agent-config-manager'

const NOTE = `${MARKER}. \`agent-config uninstall-commands\` removes this file; \`agent-config install-commands\` rewrites it.`

const DESCRIPTION = 'Open Agent Config Manager, the local web panel for this machine\'s coding-agent setup (plugins, skills, agents, MCP servers, hooks).'

const STEPS = `Open Agent Config Manager for the user:

1. Run \`agent-config start\` in a terminal, as a background process: it is a local server that keeps running until it is stopped, so do not wait for it to exit.
2. Wait until it prints a link that starts with \`http://127.0.0.1:\` and contains \`#token=\`.
3. Give the user that link exactly as printed, and tell them the panel stays available while the process runs. It also opens in their browser.

If it reports that the port is in use, run \`agent-config start --port 4322\` instead (or another free port).
If the \`agent-config\` command is not found, tell the user to install it: clone the agent-config-manager repository and run \`npm link\` in it (Node.js 23.6 or newer).`

const skill = (frontMatter: string) => `---
name: agent-config
description: ${DESCRIPTION} Use only when the user asks for it explicitly.
${frontMatter}---

<!-- ${NOTE} -->

${STEPS}
`

export interface CommandFile {
  agent: AgentId
  /** The agent's config folder; `--agent all` skips agents where it does not exist. */
  configDir: string
  path: string
  content: string
}

/** The file each agent gets, for the user whose home folder is `home`. */
export function commandFiles(home: string): CommandFile[] {
  const files: Record<AgentId, Omit<CommandFile, 'agent'>> = {
    // Claude Code: a user skill; its folder name is the command, run as /agent-config. Custom commands were merged
    // into skills and skills are recommended for new work. disable-model-invocation keeps it to explicit use.
    // Source: https://code.claude.com/docs/en/slash-commands
    claude: {
      configDir: join(home, '.claude'),
      path: join(home, '.claude', 'skills', 'agent-config', 'SKILL.md'),
      content: skill('disable-model-invocation: true\nallowed-tools: Bash(agent-config start) Bash(agent-config start *)\n')
    },
    // Codex: a user skill (name and description are required), run as $agent-config or picked from /skills. Custom
    // prompts (~/.codex/prompts, /prompts:name) are deprecated in favor of skills.
    // Sources: https://learn.chatgpt.com/docs/build-skills and https://learn.chatgpt.com/docs/custom-prompts
    // The docs name $HOME/.agents/skills as the user scope, but Copilot CLI also reads that folder; codex 0.172 also
    // loads $CODEX_HOME/skills (default ~/.codex/skills, where its bundled skill-installer puts skills), which only
    // Codex reads, so each agent sees the command once.
    codex: {
      configDir: join(home, '.codex'),
      path: join(home, '.codex', 'skills', 'agent-config', 'SKILL.md'),
      content: skill('')
    },
    // Gemini CLI: a TOML custom command; ~/.gemini/commands/agent-config.toml is run as /agent-config. `prompt` is
    // required, `description` optional. No !{...} shell injection: the server never exits, so it would hang.
    // Source: https://geminicli.com/docs/cli/custom-commands/
    gemini: {
      configDir: join(home, '.gemini'),
      path: join(home, '.gemini', 'commands', 'agent-config.toml'),
      content: `# ${NOTE}\ndescription = ${JSON.stringify(DESCRIPTION)}\nprompt = """\n${STEPS}\n"""\n`
    },
    // Copilot CLI: a personal skill in ~/.copilot/skills/<name>/SKILL.md (name and description required, name
    // lowercase with hyphens), run as /agent-config.
    // Source: https://docs.github.com/en/copilot/how-tos/copilot-cli/customize-copilot/add-skills
    copilot: {
      configDir: join(home, '.copilot'),
      path: join(home, '.copilot', 'skills', 'agent-config', 'SKILL.md'),
      content: skill('')
    }
  }
  return AGENTS.map((agent) => ({ agent, ...files[agent] }))
}

/** What the installer needs from the disk: the FileSystem port plus removal, which the port does not offer. */
export interface InstallerFs extends Pick<FileSystem, 'readText' | 'writeText' | 'realPath'> {
  /** Deletes one file. */
  remove(path: string): Promise<void>
  /** Deletes a folder only when it is empty; does nothing otherwise. */
  removeEmptyDir(path: string): Promise<void>
}

export const nodeInstallerFs: InstallerFs = {
  readText: nodeFileSystem.readText,
  writeText: nodeFileSystem.writeText,
  realPath: nodeFileSystem.realPath,
  remove: (path) => rm(path),
  async removeEmptyDir(path) {
    try {
      await rmdir(path)
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code
      if (code !== 'ENOTEMPTY' && code !== 'EEXIST' && code !== 'ENOENT') throw error
    }
  }
}

export type Status = 'written' | 'updated' | 'unchanged' | 'would-write' | 'skipped' | 'refused' | 'removed' | 'would-remove' | 'absent'

export interface Outcome {
  agent: AgentId
  path: string
  status: Status
  reason?: string
}

const NOT_OURS = 'the file exists and was not created by agent-config; move it away first'

const selected = (home: string, agents: AgentId[] | 'all') =>
  commandFiles(home).filter((file) => agents === 'all' || agents.includes(file.agent))

/** Creates each agent's command file. `all` covers the agents whose config folder exists. */
export async function installCommands(fs: InstallerFs, home: string, agents: AgentId[] | 'all', { dryRun }: { dryRun: boolean }): Promise<Outcome[]> {
  const outcomes: Outcome[] = []
  for (const file of selected(home, agents)) {
    const { agent, path } = file
    if (agents === 'all' && (await fs.realPath(file.configDir)) === null) {
      outcomes.push({ agent, path, status: 'skipped', reason: `${file.configDir} does not exist` })
      continue
    }
    const existing = await fs.readText(path)
    if (existing !== null && !existing.includes(MARKER)) outcomes.push({ agent, path, status: 'refused', reason: NOT_OURS })
    else if (existing === file.content) outcomes.push({ agent, path, status: 'unchanged' })
    else if (dryRun) outcomes.push({ agent, path, status: 'would-write' })
    else {
      await fs.writeText(path, file.content)
      outcomes.push({ agent, path, status: existing === null ? 'written' : 'updated' })
    }
  }
  return outcomes
}

/** Removes the command files the installer created; any other file is left alone. */
export async function uninstallCommands(fs: InstallerFs, home: string, agents: AgentId[] | 'all', { dryRun }: { dryRun: boolean }): Promise<Outcome[]> {
  const outcomes: Outcome[] = []
  for (const { agent, path } of selected(home, agents)) {
    const existing = await fs.readText(path)
    if (existing === null) outcomes.push({ agent, path, status: 'absent' })
    else if (!existing.includes(MARKER)) outcomes.push({ agent, path, status: 'refused', reason: NOT_OURS.replace('; move it away first', '') })
    else if (dryRun) outcomes.push({ agent, path, status: 'would-remove' })
    else {
      await fs.remove(path)
      // A skill lives in its own folder: drop it too when nothing else is in it.
      if (path.endsWith('SKILL.md')) await fs.removeEmptyDir(dirname(path))
      outcomes.push({ agent, path, status: 'removed' })
    }
  }
  return outcomes
}
